TouchEvent touchPoll();      /* คืน EV_NONE ถ้ายังไม่มีอะไรเกิดขึ้น */
bool       touchHeldB();     /* ปุ่ม B ถูกกดค้างอยู่ตอนนี้หรือไม่ (ใช้ไล่ความสว่าง) */
