/* =======================================================================
   touch.h - ระบบสัมผัส

   ESP8266 ไม่มี capacitive touch peripheral ในตัว (ต่างจาก ESP32 ที่มี T0-T9)
   จึงรองรับ 2 ทาง แล้วแปลงเป็น event ชุดเดียวกันให้ผู้เรียกใช้:

     TTP223  (ค่าเริ่มต้น) - โมดูลภายนอก 2 ตัว -> D1 (A) และ D2 (B)
                             จั๊มเปอร์ A และ B บนโมดูลต้อง "ไม่บัดกรี"
                             (momentary + active HIGH) ไม่งั้น long-press พัง
     XPT2046 - จอที่มีทัชสกรีนในตัว แบ่งครึ่งจอซ้าย = ปุ่ม A ขวา = ปุ่ม B

   เปลี่ยนโหมดด้วย #define USE_XPT2046 ใน config.h
   ======================================================================= */
#pragma once
#include <Arduino.h>
#include "config.h"

